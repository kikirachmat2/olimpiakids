--    - Type: HTTP Request
--    - Method: POST
--    - URL: https://script.google.com/macros/s/<DEPLOYMENT_ID>/exec
--    - Headers: Content-Type: application/json
--
-- 2. Webhook Sesi Lomba (race_events -> Google Sheets):
