-- 1. Tabel participants (Daftar Peserta Bayi)
CREATE TABLE IF NOT EXISTS participants (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  bib_number TEXT UNIQUE NOT NULL,
  age_months INTEGER,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabel race_events (Event/Babak Perlombaan, misal Heat 1, Heat 2, Final)
CREATE TABLE IF NOT EXISTS race_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  status TEXT DEFAULT 'idle' CHECK (status IN ('idle', 'running', 'finished')),
  start_time TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabel race_results (Hasil Pencatatan Waktu Tiap Peserta di Suatu Event)
CREATE TABLE IF NOT EXISTS race_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  participant_id BIGINT NOT NULL REFERENCES participants(id) ON DELETE CASCADE,
  race_event_id BIGINT NOT NULL REFERENCES race_events(id) ON DELETE CASCADE,
  finish_time TIMESTAMPTZ DEFAULT NOW(),
  duration_ms INTEGER,
  status TEXT DEFAULT 'finished' CHECK (status IN ('finished', 'disqualified')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  CONSTRAINT unique_participant_per_event UNIQUE (participant_id, race_event_id)
);

-- Indexes untuk optimasi query pencatatan dan leaderboard
CREATE INDEX IF NOT EXISTS idx_race_results_event_duration ON race_results(race_event_id, duration_ms ASC);
CREATE INDEX IF NOT EXISTS idx_race_events_status ON race_events(status);
CREATE INDEX IF NOT EXISTS idx_participants_bib ON participants(bib_number);

-- Enable Row Level Security (RLS)
ALTER TABLE participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE race_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE race_results ENABLE ROW LEVEL SECURITY;

-- Kebijakan akses publik (Read & Write untuk anon agar panitia & penonton bisa akses langsung tanpa login terpisah)
CREATE POLICY "Public read participants" ON participants FOR SELECT USING (true);
CREATE POLICY "Public insert participants" ON participants FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update participants" ON participants FOR UPDATE USING (true);
CREATE POLICY "Public delete participants" ON participants FOR DELETE USING (true);

CREATE POLICY "Public read race_events" ON race_events FOR SELECT USING (true);
CREATE POLICY "Public insert race_events" ON race_events FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update race_events" ON race_events FOR UPDATE USING (true);
CREATE POLICY "Public delete race_events" ON race_events FOR DELETE USING (true);

CREATE POLICY "Public read race_results" ON race_results FOR SELECT USING (true);
CREATE POLICY "Public insert race_results" ON race_results FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update race_results" ON race_results FOR UPDATE USING (true);
CREATE POLICY "Public delete race_results" ON race_results FOR DELETE USING (true);

-- Enable Realtime pada tabel yang didengarkan oleh leaderboard
ALTER PUBLICATION supabase_realtime ADD TABLE race_events;
ALTER PUBLICATION supabase_realtime ADD TABLE race_results;
